export function getSectionCopy(key, lang, fallbackLabel) {
  const copy = SECTION_META[key]?.[lang]
  const enrich = SECTION_ENRICHMENT[key]?.[lang] || {}
  if (copy) {
    return { ...copy, ...enrich }
  }
  return {
    title: fallbackLabel || key,
    intro: lang === 'en'
      ? `Built-in PageBuilder section \`${key}\`.`
      : `Встроенная секция PageBuilder \`${key}\`.`,
    use: '',
    output: '',
  }
}

export function fieldLabel(field, lang) {
  if (lang === 'en') {
    return field.label || field.name || '—'
  }
  if (field.label && FIELD_LABEL_RU[field.label]) {
    return FIELD_LABEL_RU[field.label]
  }
  if (field.name && FIELD_NAME_RU[field.name]) {
    return FIELD_NAME_RU[field.name]
  }
  return field.label || field.name || '—'
}

